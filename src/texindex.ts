// What the project contains that the paper can refer to: labels, bibliography keys, notebook
// figures and exported values. Feeds completion and the Figures panel.
import { invoke } from "@tauri-apps/api/core";
import { NOTEBOOK_SOURCE, root, VIEWABLE } from "./core";
import { NotebookInfo } from "./types";

export interface BibEntry { key: string; title: string; /** The .bib file it is in. */ file: string; /** 1-based. */ line: number; }
/** How a notebook was last run, as recorded by the batch runner. */
export interface RunInfo { date: string; python: string; packages: Record<string, string>; commit: string; seed: string | null; }
export interface FigureEntry { id: string; notebook: string; stale: boolean; used: boolean; }
export interface ValueEntry { name: string; notebook: string; value: string | null; used: boolean; }

export interface ProjectIndex {
  labels: string[];
  bib: BibEntry[];
  /** Citation keys the paper uses. */
  cited: string[];
  figures: FigureEntry[];
  values: ValueEntry[];
  /** Last run of each notebook, keyed by its path. */
  runs: Record<string, RunInfo>;
  /** .tex files, for \input and \include. */
  texFiles: string[];
  /** Images and PDFs, for \includegraphics. */
  graphics: string[];
}

/** Generated by notebook runs; never a paper, never something to index. */
export const VALUES_TEX = "scribe-values.tex";

const empty = (): ProjectIndex =>
  ({ labels: [], bib: [], cited: [], figures: [], values: [], runs: {}, texFiles: [], graphics: [] });

export let index: ProjectIndex = empty();

// ----- pure scanners -----

/** Drops `% comments`, keeping escaped \%. */
export const stripComments = (tex: string) => tex.replace(/(^|[^\\])%.*$/gm, "$1");

const unique = (list: string[]) => [...new Set(list)];

export const scanLabels = (tex: string) =>
  unique([...stripComments(tex).matchAll(/\\label\{([^{}]+)\}/g)].map((m) => m[1].trim()));

export function scanBib(bib: string, file = ""): BibEntry[] {
  const entries: BibEntry[] = [];
  const starts = [...bib.matchAll(/@(\w+)\s*\{\s*([^,\s{}]+)\s*,/g)];
  starts.forEach((m, i) => {
    if (/^(comment|string|preamble)$/i.test(m[1])) return;
    const body = bib.slice(m.index!, starts[i + 1]?.index ?? bib.length);
    const title = /\btitle\s*=\s*[{"]+([^}"]+)/i.exec(body)?.[1] ?? "";
    const line = bib.slice(0, m.index!).split("\n").length;
    entries.push({ key: m[2], title: title.replace(/\s+/g, " ").trim(), file, line });
  });
  return entries;
}

/** Figure ids the source pulls in, by \nbfig{id} or by including figures/id directly. */
export const scanFigureUses = (tex: string) => {
  const clean = stripComments(tex);
  return unique([
    ...[...clean.matchAll(/\\nbfig\{([^{}]+)\}/g)].map((m) => m[1].trim()),
    ...[...clean.matchAll(/\\includegraphics(?:\[[^\]]*\])?\{(?:\.\/)?figures\/([^{}]+?)(?:\.pdf)?\}/g)].map((m) => m[1]),
  ]);
};

export const scanValueUses = (tex: string) =>
  unique([...stripComments(tex).matchAll(/\\nb(?:val|table|math)\{([^{}]+)\}/g)].map((m) => m[1].trim()));

/** Citation keys used by \\cite and its relatives. */
export const scanCites = (tex: string) =>
  unique(
    [...stripComments(tex).matchAll(/\\(?:[a-zA-Z]*cite[a-zA-Z]*)\*?(?:\[[^\]]*\])*\{([^{}]+)\}/g)]
      .flatMap((m) => m[1].split(","))
      .map((key) => key.trim())
      .filter(Boolean),
  );

export interface OutlineItem {
  kind: "heading" | "figure" | "table" | "input";
  /** Headings: 0 for \\part down to 5 for \\paragraph. */
  level: number;
  /** Heading text, caption, or (for inputs) the file named. */
  title: string;
  /** 1-based. */
  line: number;
}

const HEADING_LEVEL: Record<string, number> = { part: 0, chapter: 1, section: 2, subsection: 3, subsubsection: 4, paragraph: 5 };

/** The text inside the braces that open at `open`, following nested braces. */
function braced(text: string, open: number): string {
  let depth = 0;
  for (let i = open; i < text.length; i++) {
    if (text[i] === "\\") { i++; continue; }
    if (text[i] === "{") depth++;
    else if (text[i] === "}" && --depth === 0) return text.slice(open + 1, i);
  }
  return text.slice(open + 1);
}

/** Readable text from a LaTeX fragment: formatting commands dropped, their contents kept. */
const plain = (tex: string) =>
  tex.replace(/\\(?:label|ref|cite\w*)\{[^{}]*\}/g, "").replace(/\\[a-zA-Z]+\*?|[{}~]|\\\\/g, " ").replace(/\s+/g, " ").trim();

/** Headings, floats and \\input lines of one file, in order. */
export function scanOutline(tex: string): OutlineItem[] {
  const items: OutlineItem[] = [];
  const lines = stripComments(tex).split("\n");
  let float: OutlineItem | null = null;
  lines.forEach((text, i) => {
    const line = i + 1;
    const heading = /\\(part|chapter|section|subsection|subsubsection|paragraph)\*?(?:\[[^\]]*\])?\{/.exec(text);
    if (heading) {
      // A title can run over several lines; look ahead a little for its closing brace.
      const rest = lines.slice(i, i + 4).join(" ");
      const title = plain(braced(rest, rest.indexOf("{", rest.indexOf(heading[0]))));
      items.push({ kind: "heading", level: HEADING_LEVEL[heading[1]], title: title || heading[1], line });
    }
    const input = /\\(?:input|include|subfile)\{([^{}]+)\}/.exec(text);
    if (input) items.push({ kind: "input", level: 0, title: input[1].trim(), line });

    const begin = /\\begin\{(figure|table)\*?\}/.exec(text);
    if (begin) {
      float = { kind: begin[1] as "figure" | "table", level: 0, title: begin[1] === "figure" ? "Figure" : "Table", line };
      items.push(float);
    }
    if (float) {
      const caption = text.indexOf("\\caption");
      if (caption !== -1) {
        const rest = lines.slice(i, i + 4).join(" ");
        const open = rest.indexOf("{", rest.indexOf("\\caption"));
        if (open !== -1) float.title = plain(braced(rest, open)) || float.title;
      }
      if (/\\end\{(figure|table)\*?\}/.test(text)) float = null;
    }
  });
  return items;
}

export interface NoteItem { kind: "TODO" | "FIXME" | "NOTE"; text: string; line: number; }

/** Notes left for later: `% TODO: ...`, `% FIXME ...`, `% NOTE ...` comments and \\todo{...}. */
export function scanNotes(tex: string): NoteItem[] {
  const notes: NoteItem[] = [];
  tex.split("\n").forEach((text, i) => {
    const comment = /(?:^|[^\\])%+\s*(TODO|FIXME|NOTE|XXX)\b[:\s-]*(.*)$/i.exec(text);
    if (comment) {
      const kind = comment[1].toUpperCase();
      notes.push({ kind: kind === "XXX" ? "FIXME" : (kind as NoteItem["kind"]), text: comment[2].trim(), line: i + 1 });
      return;
    }
    const command = /\\(todo|fixme)(?:\[[^\]]*\])?\{/i.exec(stripComments(text));
    if (command) {
      const open = text.indexOf("{", text.indexOf(command[0]));
      notes.push({ kind: command[1].toLowerCase() === "fixme" ? "FIXME" : "TODO", text: plain(braced(text, open)), line: i + 1 });
    }
  });
  return notes;
}

/** A stored value as a person would read it: without the LaTeX escaping, tables as one word. */
export function displayValue(value: string | null): string {
  if (value === null) return "not run yet";
  if (value.includes("\\begin{tabular}")) return "table";
  return value
    // siunitx numbers: \qty{3.21 +- 0.04 e-5}{kg} reads as 3.21 ± 0.04 ×10^-5 kg
    .replace(/\\(?:qty|num)\{([^{}]*)\}(?:\{([^{}]*)\})?/g, (_m, number: string, unit?: string) =>
      number.replace(/\s*\+-\s*/, " ± ").replace(/\s*e\+?(-?\d+)/, " ×10^$1") + (unit ? " " + unit.replace(/\\percent/g, "%") : ""))
    .replace(/~?\\unit\{([^{}]*)\}/g, " $1")
    .replace(/\\([%&#_$])/g, "$1");
}

// ----- project scan -----

let job = 0;

/** Re-reads the project. Cheap enough to call after saves, compiles and notebook runs. */
export async function refreshIndex(): Promise<ProjectIndex> {
  if (!root) {
    index = empty();
    return index;
  }
  const mine = ++job;
  const read = (rel: string) => invoke<string>("read_file", { root, rel }).catch(() => "");
  const files = await invoke<string[]>("list_files", { root }).catch(() => [] as string[]);

  const next = empty();
  next.texFiles = files.filter((f) => f.endsWith(".tex") && f !== VALUES_TEX);
  next.graphics = files.filter((f) => VIEWABLE.test(f));

  const usedFigures = new Set<string>();
  const usedValues = new Set<string>();
  for (const tex of await Promise.all(next.texFiles.map(read))) {
    next.labels.push(...scanLabels(tex));
    scanFigureUses(tex).forEach((id) => usedFigures.add(id));
    scanValueUses(tex).forEach((name) => usedValues.add(name));
    next.cited.push(...scanCites(tex));
  }
  next.cited = unique(next.cited);
  next.labels = unique(next.labels).sort();

  const bibFiles = files.filter((f) => f.endsWith(".bib"));
  (await Promise.all(bibFiles.map(read))).forEach((bib, i) => next.bib.push(...scanBib(bib, bibFiles[i])));

  // Values as last written by a notebook run, keyed by notebook.
  let store: Record<string, Record<string, string>> = {};
  try {
    store = JSON.parse(await read(".scribe/values.json")) ?? {};
  } catch { /* none written yet */ }
  try {
    next.runs = JSON.parse(await read(".scribe/runs.json")) ?? {};
  } catch { /* no notebook has run yet */ }

  for (const notebook of files.filter((f) => NOTEBOOK_SOURCE.test(f))) {
    const info = await invoke<NotebookInfo>("parse_notebook", { root, rel: notebook }).catch(() => null);
    if (!info) continue;
    for (const id of info.figure_ids) {
      next.figures.push({ id, notebook, stale: info.stale.includes(id), used: usedFigures.has(id) });
    }
    for (const name of info.value_names ?? []) {
      next.values.push({ name, notebook, value: store[notebook]?.[name] ?? null, used: usedValues.has(name) });
    }
  }

  if (mine === job) index = next; // a newer scan may have finished first
  return next;
}

let timer: number | null = null;

/** For callers that fire often (every save): one scan after things settle. */
export function refreshIndexSoon() {
  if (timer) clearTimeout(timer);
  timer = window.setTimeout(() => {
    refreshIndex().catch(() => {});
  }, 400);
}
